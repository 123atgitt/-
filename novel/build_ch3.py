NAME_FIX = {
    "陆·赫斯": "陸赫斯",
    "陆赫斯": "陸赫斯",
    "陸·赫斯": "陸赫斯",
    "魏尔伦": "沃倫",
    "魏爾倫": "沃倫",
    "准时宝": "「準時寶」",
    "N.A.N.A.": "N.A.N.A.",
    "？？？": "未知聲音",
}


def fix_names(s: str) -> str:
    for a, b in NAME_FIX.items():
        s = s.replace(a, b)
    return s


def s2t(s: str) -> str:
    return fix_names(cc.convert(s))


def format_dialogue_line(line: str, player_style: str = "mix") -> str | None:
    line = line.strip()
    if not line or "：" not in line:
        return None
    if SKIP_PATTERNS.search(line):
        return None
    # narrative blurbs in wiki
    if line.startswith("漂泊者：（") and line.endswith("）"):
        inner = line[len("漂泊者：（") : -1]
        return s2t(f"你心想：{inner}")
    if line.startswith("漂泊者：") and line.endswith("漂泊者："):
        return None
    parts = line.split("：", 1)
    if len(parts) != 2:
        return None
    speaker, text = parts[0].strip(), parts[1].strip()
    if not text:
        return "——"  # player choice pause
    speaker = s2t(speaker)
    text = s2t(text)
    if speaker in ("漂泊者", "你"):
        if text in ("", "……"):
            return None
        if text.startswith("（") and text.endswith("）"):
            return s2t(f"你{ text[1:-1] }。")
        if len(text) < 18 and "？" not in text and "?" not in text:
            return f"「{text}」"
        return f"「{text}」你說。"
    if "（通讯中）" in speaker or "（通訊中）" in speaker:
        speaker = speaker.replace("（通讯中）", "").replace("（通訊中）", "").strip()
        return f"{speaker}的聲音從終端裡傳來：「{text}」"
    return f"{speaker}：「{text}」"


def process_wiki(path: Path, sample_skip: int = 0, max_lines: int = 180) -> list[str]:
    """sample_skip: keep line if i % (sample_skip+1) == 0 OR important."""
    raw = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    out: list[str] = []
    dlg_i = 0
    for line in raw:
        if len(out) >= max_lines:
            break
        if "：" not in line:
            continue
        if DROP_LINE.search(line):
            continue
        if SKIP_PATTERNS.search(line.strip()):
            continue
        dlg_i += 1
        keep = IMPORTANT.search(line) or sample_skip == 0 or (dlg_i % (sample_skip + 1) == 1)
        if not keep:
            continue
        formatted = format_dialogue_line(line)
        if formatted:
            out.append(formatted)
    return out


